// Bundles one AapStack function per job source into aapstack/functions/sync-<slug>.mjs (single ESM file,
// no imports left — AapStack functions are one module, ≤ 512 KB).
//   npx tsx scripts/aapstack/build-functions.ts
import { build } from "esbuild";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SYNC_SOURCES = ["himalayas", "jobicy", "remoteok", "startupjobs", "remotive", "adzuna", "freelancer", "workingnomads", "arbeitnow", "greenhouse", "lever", "ashby", "weworkremotely", "jooble"];

const syncEntry = fileURLToPath(new URL("./function-entry.ts", import.meta.url));
const embedEntry = fileURLToPath(new URL("./embed-entry.ts", import.meta.url));
const targets: Array<[string, string, Record<string, string>]> = [
  ...SYNC_SOURCES.map((slug): [string, string, Record<string, string>] => [`sync-${slug}`, syncEntry, { __SOURCE_SLUG__: JSON.stringify(slug) }]),
  ["embed-jobs", embedEntry, {}],
];
for (const [name, entry, define] of targets) {
  const outfile = fileURLToPath(new URL(`../../aapstack/functions/${name}.mjs`, import.meta.url));
  await build({
    entryPoints: [entry], outfile, bundle: true, format: "esm", platform: "node", target: "node22", minify: true,
    define, legalComments: "none", logLevel: "warning",
    banner: { js: `// ${name} — generated by scripts/aapstack/build-functions.ts; do not edit.` },
  });
  // AapStack's deploy API looks for a literal `export default`; minified ESM writes `export{x as default}`.
  const code = readFileSync(outfile, "utf8");
  const m = code.match(/export\s*\{\s*([\w$]+)\s+as\s+default\s*\};?\s*$/);
  if (!m) throw new Error(`${name}: no default export found`);
  writeFileSync(outfile, code.slice(0, m.index) + `export default ${m[1]};\n`);
  const kb = statSync(outfile).size / 1024;
  if (kb > 500) throw new Error(`${name} is ${kb.toFixed(0)} KB (limit 512 KB)`);
  console.log(`aapstack/functions/${name}.mjs  ${kb.toFixed(0)} KB`);
}
